// Shared pure helper: the UI and exported prompt table use the same scene descriptions.
window.APP_HELPERS = {
  buildPrompt(character, background) {
    const { types, styles } = window.APP_DATA;
    const style = styles.find((item) => item.id === character.styleId);
    if (character.scenes) {
      const scene = character.scenes[background.id];
      if (!scene || background.typeId !== character.typeId || (["male", "female", "mecha"].includes(character.typeId) && background.roleId !== character.roleId)) throw new Error("這位角色沒有此專屬場景");
      if (character.typeId === "male") {
        return "一位少年冒險家「" + character.roleName + "」，有著" + character.appearance + "，在" + background.scene + "，" + scene.action + "，以" + style.prompt + "呈現。";
      }
      if (character.typeId === "mecha") {
        return "機甲戰士「" + character.roleName + "」，具有" + character.appearance + "，置身" + background.scene + "，" + scene.action + "，以" + style.prompt + "呈現。";
      }
      if (character.typeId === "pokemon") {
        return "寶可夢「" + character.roleName + "」，具有" + character.appearance + "，置身" + background.scene + "，" + scene.action + "，以" + style.prompt + "呈現。";
      }
      return "一位友善的少女「" + character.roleName + "」，有著" + character.appearance + "，在" + background.scene + "，" + scene.action + "，以" + style.prompt + "呈現。";
    }
    if (background.typeId !== character.typeId) throw new Error("角色類型與場景不相符");
    const type = types.find((item) => item.id === character.typeId);
    return "一位" + type.name.replace("角色", "") + "的「" + character.roleName + "」，具有" + character.appearance + "，在" + background.scene + character.action + "，以" + style.prompt + "呈現。";
  },
};
